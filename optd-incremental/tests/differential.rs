//! The differential test: **incremental maintenance must agree with a full
//! recompute, after every batch, for every view shape.**
//!
//! This is the only claim that matters. A delta rule that is wrong usually still
//! *runs* and still produces plausible-looking rows — the algebra is easy to get
//! subtly wrong (a missing `ΔA⋈ΔB`, a retraction applied with the wrong sign, a
//! group that should have been dropped). Comparing against an evaluation of the
//! same plan over the current data is what turns "looks right" into "tested".
//!
//! Change batches are generated by a small deterministic LCG rather than a
//! randomness crate: the sequence must be reproducible when a failure is found.

use optd_incremental::change::{Capabilities, Row, Value};
use optd_incremental::engine::View;
use optd_incremental::plan::{agg, filter, join, project, scan, union, AggKind, Expr, IncPlanNode};
use optd_incremental::source::InMemorySource;

const T_A: u32 = 0;
const T_B: u32 = 1;

fn row(vals: &[i64]) -> Row {
    vals.iter().map(|v| Value::Int(*v)).collect()
}

/// Deterministic pseudo-random source of changes.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        self.0 >> 33
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

/// Apply one random batch: inserts and (crucially) deletes on both tables.
///
/// Deletes are what separate a real delta rule from an insert-only one, so the
/// generator must produce them, and must sometimes delete a row that is
/// currently present rather than always a fresh one.
fn random_batch(src: &mut InMemorySource, rng: &mut Lcg, live_a: &mut Vec<Row>, live_b: &mut Vec<Row>) {
    let mut batch: Vec<(u32, Row, i64)> = Vec::new();

    for _ in 0..rng.below(4) + 1 {
        let r = row(&[rng.below(6) as i64, rng.below(4) as i64]);
        batch.push((T_A, r.clone(), 1));
        live_a.push(r);
    }
    for _ in 0..rng.below(3) + 1 {
        let r = row(&[rng.below(5) as i64]);
        batch.push((T_B, r.clone(), 1));
        live_b.push(r);
    }
    // Deletes: only of rows that exist, so the multiset never goes negative.
    if !live_a.is_empty() && rng.below(2) == 0 {
        let i = rng.below(live_a.len() as u64) as usize;
        batch.push((T_A, live_a.remove(i), -1));
    }
    if !live_b.is_empty() && rng.below(2) == 0 {
        let i = rng.below(live_b.len() as u64) as usize;
        batch.push((T_B, live_b.remove(i), -1));
    }

    src.apply_batch(batch);
}

fn seed(src: &mut InMemorySource, live_a: &mut Vec<Row>, live_b: &mut Vec<Row>) {
    for a in 0..6i64 {
        for b in 0..4i64 {
            let r = row(&[a, b]);
            src.insert(T_A, r.clone());
            live_a.push(r);
        }
    }
    for b in 0..5i64 {
        let r = row(&[b]);
        src.insert(T_B, r.clone());
        live_b.push(r);
    }
}

/// Drive a view through many batches, asserting agreement with a recompute each time.
fn run_differential(name: &str, plan: IncPlanNode, batches: usize) {
    let mut src = InMemorySource::new(Capabilities::change_log());
    let mut live_a = Vec::new();
    let mut live_b = Vec::new();
    seed(&mut src, &mut live_a, &mut live_b);

    let mut view = View::load(plan, &src, vec![T_A, T_B])
        .unwrap_or_else(|e| panic!("{}: LOAD failed: {}", name, e));

    // LOAD itself must agree with a recompute.
    assert_eq!(
        view.contents(),
        &view.recompute(&src).unwrap(),
        "{}: after LOAD",
        name
    );

    let mut rng = Lcg(0x5eed_1234_abcd_9876);
    for i in 0..batches {
        random_batch(&mut src, &mut rng, &mut live_a, &mut live_b);
        view.refresh(&src)
            .unwrap_or_else(|e| panic!("{}: refresh {} failed: {}", name, i, e));

        let incremental = view.contents().clone();
        let recomputed = view.recompute(&src).unwrap();
        assert_eq!(
            incremental, recomputed,
            "{}: incremental and recomputed views diverged at batch {}\n  incremental: {:?}\n  recomputed:  {:?}",
            name, i, incremental, recomputed
        );
    }
}

#[test]
fn projection_and_filter_agree_with_recompute() {
    let plan = project(filter(scan(T_A), Expr::Gt(Box::new(Expr::Col(1)), Box::new(Expr::Lit(Value::Int(1))))), vec![0]);
    run_differential("filter+project", plan, 40);
}

#[test]
fn inner_join_agrees_with_recompute() {
    // Δ(A⋈B) is the rule that needs both snapshot handling and the weights to
    // multiply; it is the most likely place for a sign or a doubled row.
    let plan = join(scan(T_A), scan(T_B), vec![(1, 0)]);
    run_differential("inner join", plan, 40);
}

#[test]
fn join_then_project_agrees_with_recompute() {
    let plan = project(join(scan(T_A), scan(T_B), vec![(1, 0)]), vec![0, 2]);
    run_differential("join+project", plan, 40);
}

#[test]
fn union_agrees_with_recompute() {
    let plan = union(scan(T_A), scan(T_A));
    run_differential("union", plan, 30);
}

#[test]
fn aggregate_agrees_with_recompute() {
    // The terminal rule: a group also holds the unchanged rows contributing to it,
    // so Agg(ΔX) alone is wrong. Deletes exercise the group-dropping path.
    let plan = agg(scan(T_A), vec![0], vec![AggKind::Count, AggKind::Sum(1)]);
    run_differential("aggregate", plan, 40);
}

#[test]
fn filter_then_aggregate_agrees_with_recompute() {
    let plan = agg(
        filter(scan(T_A), Expr::Gt(Box::new(Expr::Col(1)), Box::new(Expr::Lit(Value::Int(0))))),
        vec![0],
        vec![AggKind::Count, AggKind::Sum(1)],
    );
    run_differential("filter+aggregate", plan, 40);
}

/// A view whose data is never mutated can be maintained from a feed that cannot
/// express deletes; one whose data *is* mutated cannot.
///
/// This is the capability guard of `change_capture.md` §7, and the failure mode it
/// prevents is silent staleness rather than an error.
#[test]
fn a_feed_without_deletes_is_refused_rather_than_assumed() {
    let mut src = InMemorySource::new(Capabilities::version_column());
    src.insert(T_A, row(&[1, 1]));
    let plan = project(scan(T_A), vec![0]);
    let err = View::load(plan, &src, vec![T_A]).unwrap_err();
    let msg = err.to_string();
    assert!(
        msg.contains("expresses_deletes"),
        "expected the capability guard to fire, got: {}",
        msg
    );
}

/// A multi-table view on a feed without cross-table positions is torn: the two
/// tables' before/after states do not correspond to any single point in time.
#[test]
fn a_multi_table_view_requires_cross_table_positions() {
    let mut src = InMemorySource::new(Capabilities::snapshot_diff());
    src.insert(T_A, row(&[1, 1]));
    src.insert(T_B, row(&[1]));
    let plan = join(scan(T_A), scan(T_B), vec![(1, 0)]);
    let err = View::load(plan, &src, vec![T_A, T_B]).unwrap_err();
    assert!(err.to_string().contains("cross_table_position"));
}

/// An operator outside milestone 1 must be refused, not silently mishandled.
#[test]
fn an_unsupported_operator_is_refused() {
    use optd_incremental::plan::stored_view;
    let mut src = InMemorySource::new(Capabilities::change_log());
    src.insert(T_A, row(&[1, 1]));
    // A view defined in terms of itself is not representable; the point is that
    // the failure is an error and not a wrong result.
    let err = View::load(stored_view(), &src, vec![T_A]).unwrap_err();
    assert!(matches!(err, optd_incremental::RefreshError::CannotMaintain(_)));
}